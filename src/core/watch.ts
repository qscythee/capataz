import { layouts, routeFile } from './layout';
import { watch } from 'node:fs';
import { nodeFs, ProjectFs } from './fs';
import { defaultProjectFile, generate, projectFilePath, readConfig } from './project';
import { CapatazConfig } from '../config';
import { Analysis } from '../lint/analyze';
import { TargetLinter } from '../lint/targets';

async function regenerate(fs: ProjectFs, config: CapatazConfig): Promise<boolean> {
	let changed = false;
	for (const layout of layouts(config)) { changed = await generate(fs, layout) || changed; }
	return changed;
}

export async function prepareWatch(fs: ProjectFs, config: CapatazConfig, target?: string) {
	const generatedFile = defaultProjectFile(config);
	const projectFile = target === undefined ? generatedFile : projectFilePath(target);
	if (projectFile !== generatedFile && !Object.values(config.projects ?? {}).some(layout => layout.projectFile === projectFile)) {
		if (!(await fs.exists(projectFile))) { throw new Error(`Selected project '${projectFile}' does not exist. Only '${generatedFile}' is generated by Capataz.`); }
		const selected = JSON.parse(await fs.read(projectFile));
		if (!selected?.tree || typeof selected.tree !== 'object') { throw new Error(`Selected project '${projectFile}' must define a Rojo tree.`); }
	}
	await regenerate(fs, config);
	return { generatedFile, projectFile };
}

/** Generates and lints only; external build/sync processes belong to the developer. */
export async function watchProject(root: string, target?: string): Promise<number> {
	const fs = nodeFs(root);
	const initialConfig = await readConfig(fs);
	const plan = await prepareWatch(fs, initialConfig, target);
	const outputPaths = (config: CapatazConfig) => new Set(layouts(config).flatMap(layout => [defaultProjectFile(layout), routeFile(layout)]));
	let generatedPaths = outputPaths(initialConfig);
	const generatedProjects = () => [...generatedPaths].filter(file => file.endsWith('.project.json')).join(', ');
	const linter = new TargetLinter(fs, target === undefined ? undefined : plan.projectFile);
	const results = new Map<string, Analysis>();
	const report = async (rebuild: boolean, files: Set<string>) => {
		const updates = await linter.refresh({ rebuild, files });
		for (const [file, result] of updates) { results.set(file, result); }
		if (!updates.size && !rebuild) { return; }
		const issues = [...results.values()].flatMap(result => result.diagnostics);
		for (const issue of issues) { console.log(`${issue.file}:${issue.line}:${issue.column}: ${issue.severity} [${issue.code}] ${issue.message}`); }
		console.log(`Lint: ${issues.filter(issue => issue.severity === 'error').length} errors, ${issues.filter(issue => issue.severity === 'warning').length} warnings.`);
	};
	// Keep watching after invalid source/project edits, so correcting them recovers.
	try { await report(true, new Set()); } catch (error) { console.error(`Capataz: ${(error as Error).message}`); }
	return new Promise(resolve => {
		let stopped = false, timer: ReturnType<typeof setTimeout> | undefined;
		let running: Promise<void> | undefined, pending = false, rebuild = false;
		const files = new Set<string>();
		const refresh = async () => {
			if (running) { pending = true; return; }
			running = (async () => {
				do {
					pending = false;
					const structural = rebuild, changed = new Set(files); rebuild = false; files.clear();
					try {
						let generated = false;
						if (structural) {
							const config = await readConfig(fs); generatedPaths = outputPaths(config);
							generated = await regenerate(fs, config);
						}
						if (generated) { console.log(`Regenerated ${generatedProjects()} and system routes`); }
						await report(structural || generated, changed);
					} catch (error) { rebuild = true; console.error(`Capataz: ${(error as Error).message}`); }
				} while (pending && !stopped);
			})();
			try { await running; } finally { running = undefined; }
		};
		const watcher = watch(root, { recursive: true }, (event, filename) => {
			const file = filename?.toString().replace(/\\/g, '/');
			if (!file || /(^|\/)(node_modules|\.git|\.capataz)(\/|$)/.test(file) || generatedPaths.has(file) || file === 'sourcemap.json' || file.endsWith('.sourcemap.json')) { return; }
			if (event !== 'rename' && !/\.lua[u]?$|\.json$|(^|\/)\.luaurc$/.test(file)) { return; }
			rebuild ||= event === 'rename' || !/\.lua[u]?$/.test(file); files.add(file);
			if (timer) { clearTimeout(timer); }
			timer = setTimeout(() => { timer = undefined; void refresh(); }, 200);
		});
		const stop = (code: number) => {
			if (stopped) { return; } stopped = true; watcher.close();
			if (timer) { clearTimeout(timer); }
			process.off('SIGINT', interrupt); process.off('SIGTERM', interrupt);
			void (running ?? Promise.resolve()).then(() => resolve(code));
		};
		const interrupt = () => stop(0);
		watcher.on('error', error => { console.error(error.message); stop(2); });
		process.on('SIGINT', interrupt); process.on('SIGTERM', interrupt);
		console.log(`Watching ${target ?? 'configured lint targets'}; generating ${generatedProjects()}. Press Ctrl+C to stop.`);
	});
}
